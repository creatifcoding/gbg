/**
 * SQL-backed work cell state implementation for production.
 *
 * Uses a repository adapter for actual SQL operations.
 * This factory bridges the state interface to the repository pattern.
 *
 * @param repo - Repository implementing work cell CRUD operations
 */
export const makeWorkCellStateSql = (repo: {
  findById: (id: WorkCellId) => Effect.Effect<Option.Option<WorkCell>, unknown>
  findAll: (filter: WorkCellFilter) => Effect.Effect<readonly WorkCell[], unknown>
  insert: (workCell: WorkCell) => Effect.Effect<WorkCell, unknown>
  update: (workCell: Partial<WorkCell> & { id: WorkCellId }) => Effect.Effect<WorkCell, unknown>
  delete: (id: WorkCellId) => Effect.Effect<boolean, unknown>
  /** Insert with DB-generated ID. If not provided, falls back to insert() */
  insertWithGeneratedId?: (params: CreateWorkCellParams) => Effect.Effect<WorkCell, unknown>
}): WorkCellStateShape => ({
  create: (params: CreateWorkCellParams) =>
    repo.insertWithGeneratedId
      ? repo.insertWithGeneratedId(params).pipe(
          Effect.orDie // SQL failures are defects
        )
      : Effect.gen(function* () {
          // Fallback: generate ID client-side if repo doesn't support generated IDs
          const id = generateWorkCellId()
          const now = yield* DateTime.now
          const workCell = new WorkCell({
            id,
            name: params.name,
            status: params.status ?? 'idle',
            description: params.description !== undefined ? Option.some(params.description) : Option.none(),
            location: Option.none(),
            metadata: params.metadata ?? {},
            createdAt: now,
            updatedAt: Option.none(),
            hierarchyPath: HierarchyPath.empty(),
            enterpriseId: Option.none(),
            siteId: Option.none(),
            areaId: Option.none(),
            plantId: Option.none(),
            lineId: Option.some(params.lineId),
            workCellId: Option.none(),
            machineId: Option.none(),
            cellType: params.cellType !== undefined ? Option.some(params.cellType) : Option.none(),
            cycleTimeSeconds: params.cycleTimeSeconds !== undefined ? Option.some(params.cycleTimeSeconds) : Option.none(),
            position: params.position !== undefined ? Option.some(params.position) : Option.none(),
          })
          return yield* repo.insert(workCell).pipe(Effect.orDie)
        }),

  get: (id) =>
    repo.findById(id).pipe(
      Effect.flatMap((opt) =>
        Option.isSome(opt)
          ? Effect.succeed(opt.value)
          : Effect.fail(new WorkCellStateNotFoundError(id))
      ),
      Effect.catchAll(() => Effect.fail(new WorkCellStateNotFoundError(id)))
    ),

  set: (workCell) =>
    repo.findById(workCell.id).pipe(
      Effect.flatMap((existing) =>
        Option.isSome(existing)
          ? repo.update(workCell as Partial<WorkCell> & { id: WorkCellId })
          : repo.insert(workCell)
      ),
      Effect.asVoid,
      Effect.catchAll(() => Effect.void)
    ),

  list: (filter) =>
    repo.findAll(filter).pipe(
      Effect.catchAll(() => Effect.succeed([]))
    ),

  delete: (id) =>
    repo.delete(id).pipe(
      Effect.catchAll(() => Effect.succeed(false))
    ),

  exists: (id) =>
    repo.findById(id).pipe(
      Effect.map(Option.isSome),
      Effect.catchAll(() => Effect.succeed(false))
    ),

  count: (filter) =>
    repo.findAll({ ...filter, limit: undefined, offset: undefined }).pipe(
      Effect.map((workCells) => workCells.length),
      Effect.catchAll(() => Effect.succeed(0))
    ),
})
