interface LinkInfo {
  apiName: string
  sourceName: string
  targetName: string
  cardinality: LinkCardinality
  foreignKeyProperty?: string
}

const generateLinkFile = (link: LinkInfo): string => {
  const { apiName, sourceName, targetName, cardinality, foreignKeyProperty } =
    link

  let linkConfig = ""
  if (cardinality === "many-to-one") {
    linkConfig = `  one: {
    object: ${targetName},
    metadata: {
      apiName: "${targetName.toLowerCase()}",
      displayName: "${targetName}",
      pluralDisplayName: "${targetName}s",
    },
  },
  toMany: {
    object: ${sourceName},
    metadata: {
      apiName: "${sourceName.toLowerCase()}s",
      displayName: "${sourceName}",
      pluralDisplayName: "${sourceName}s",
    },
  },${foreignKeyProperty ? `\n  manyForeignKeyProperty: "${foreignKeyProperty}",` : ""}`
  } else if (cardinality === "one-to-many") {
    linkConfig = `  one: {
    object: ${sourceName},
    metadata: {
      apiName: "${sourceName.toLowerCase()}",
      displayName: "${sourceName}",
      pluralDisplayName: "${sourceName}s",
    },
  },
  toMany: {
    object: ${targetName},
    metadata: {
      apiName: "${targetName.toLowerCase()}s",
      displayName: "${targetName}",
      pluralDisplayName: "${targetName}s",
    },
  },`
  } else if (cardinality === "one-to-one") {
    linkConfig = `  one: {
    object: ${sourceName},
    metadata: {
      apiName: "${sourceName.toLowerCase()}",
      displayName: "${sourceName}",
      pluralDisplayName: "${sourceName}s",
    },
  },
  toOne: {
    object: ${targetName},
    metadata: {
      apiName: "${targetName.toLowerCase()}",
      displayName: "${targetName}",
      pluralDisplayName: "${targetName}s",
    },
  },`
  } else {
    // many-to-many
    linkConfig = `  toMany: {
    object: ${targetName},
    metadata: {
      apiName: "${targetName.toLowerCase()}s",
      displayName: "${targetName}",
      pluralDisplayName: "${targetName}s",
    },
  },`
  }

  return `/**
 * ${apiName} Link
 * ${sourceName} → ${targetName} (${cardinality})
 */

import { defineLink } from "@osdk/maker";
import { ${sourceName} } from "../objects/${sourceName}.js";
import { ${targetName} } from "../objects/${targetName}.js";

export const ${apiName} = defineLink({
  apiName: "${apiName}",
${linkConfig}
});
`
}

const generateLinksIndex = (links: LinkInfo[]): string => {
  if (links.length === 0) {
    return `/**
 * Link Type Exports
 */

// No links defined
export {};
`
  }

  const exports = links
    .map((link) => `export { ${link.apiName} } from "./${link.apiName}.js";`)
    .join("\n")

  return `/**
 * Link Type Exports
 */

${exports}
`
}

