/**
 * Scaffold a complete Ontology as Code repository.
 *
 * Creates the following structure:
 * - package.json with @osdk/maker dependencies
 * - tsconfig.json for TypeScript
 * - README.md with deployment instructions
 * - ontology/ directory with object and link definitions
 * - scripts/ directory with build script
 *
 * @example
 * ```ts
 * await Effect.runPromise(
 *   scaffoldOntologyRepo({
 *     namespace: "com.mycompany.",
 *     outputPath: "./my-ontology",
 *     schemas: [Department, Employee],
 *   })
 * )
 * ```
 */
export const scaffoldOntologyRepo = (
  config: OntologyAsCodeConfig
): Effect.Effect<void, CompileError | ScaffoldError> => {
  const { outputPath, includeLinks = true } = config

  return Effect.flatMap(
    generateOntologyModule({
      namespace: config.namespace,
      schemas: config.schemas,
      includeLinks,
    }),
    (module) =>
      Effect.try({
        try: () => {
          // Create directory structure
          const dirs = [
            outputPath,
            join(outputPath, "ontology"),
            join(outputPath, "ontology", "objects"),
            join(outputPath, "ontology", "links"),
            join(outputPath, "scripts"),
          ]

          for (const dir of dirs) {
            mkdirSync(dir, { recursive: true })
          }

          // Write package files
          writeFileSync(
            join(outputPath, "package.json"),
            generatePackageJson(config)
          )
          writeFileSync(join(outputPath, "tsconfig.json"), generateTsConfig())
          writeFileSync(join(outputPath, "README.md"), generateReadme(config))

          // Write build script
          writeFileSync(
            join(outputPath, "scripts", "build.ts"),
            generateBuildScript(config)
          )

          // Write ontology module files
          Array.from(module.files.entries()).forEach(([filePath, content]) => {
            writeFileSync(join(outputPath, filePath), content)
          })

          console.log(`Ontology as Code repository scaffolded at: ${outputPath}`)
          console.log("Next steps:")
          console.log("  1. cd " + outputPath)
          console.log("  2. npm install")
          console.log("  3. npm run validate")
          console.log("  4. npm run build")
          console.log("  5. git init && git add . && git commit -m 'Initial ontology'")
          console.log("  6. git tag v" + (config.version ?? "1.0.0"))
        },
        catch: (e) =>
          new ScaffoldError(
            `Failed to scaffold repository: ${e}`,
            e
          ),
      })
  )
}

/**
 * Preview the files that would be generated without writing to disk.
 *
 * Useful for debugging or generating to alternative outputs.
 */
export const previewOntologyRepo = (
  config: OntologyAsCodeConfig
): Effect.Effect<ReadonlyMap<string, string>, CompileError> => {
  return Effect.map(
    generateOntologyModule({
      namespace: config.namespace,
      schemas: config.schemas,
      includeLinks: config.includeLinks ?? true,
    }),
    (module) => {
      const allFiles = new Map<string, string>()

      // Add package files
      allFiles.set("package.json", generatePackageJson(config))
      allFiles.set("tsconfig.json", generateTsConfig())
      allFiles.set("README.md", generateReadme(config))
      allFiles.set("scripts/build.ts", generateBuildScript(config))

      // Add ontology module files
      Array.from(module.files.entries()).forEach(([path, content]) => {
        allFiles.set(path, content)
      })

      return allFiles
    }
  )
}
