/**
 * WorkCellState Service
 *
 * Effect.Service for work cell state management with swappable implementations.
 * Provides in-memory (testing) and SQL (production) layers.
 *
 * WorkCells are ISA-95 Level 1 entities (Work Units) that sit between
 * Lines and Machines in the hierarchy.
 *
 * @module
 */

import { Effect, Context, Layer, Option, Ref, DateTime } from 'effect'
import type { WorkCellId, LineId } from '../schemas/identifiers'
import { WorkCell, CreateWorkCellParams, makeWorkCellId } from '../schemas/assets/workcell'
import { HierarchyPath } from '../schemas/hierarchy'
import type { PaginationOptions, TimeRangeFilter } from './StateShape'

// =============================================================================
// ID Generation
// =============================================================================

let workCellCounter = 0

/** Generate a unique work cell ID for in-memory testing */
const generateWorkCellId = (): WorkCellId => makeWorkCellId(`gen-${Date.now()}-${++workCellCounter}`)

// =============================================================================
// Filter & Error Types
// =============================================================================

/** Filter for listing work cells */
export interface WorkCellFilter extends PaginationOptions, TimeRangeFilter {
  /** Filter by parent line ID */
  readonly lineId?: LineId
  /** Filter by operational status */
  readonly status?: string
  /** Filter by cell type */
  readonly cellType?: string
  /** Filter only operational work cells (not maintenance/decommissioned) */
  readonly onlyOperational?: boolean
}

/** Work cell state not found error */
export class WorkCellStateNotFoundError {
  readonly _tag = 'WorkCellStateNotFoundError'
  constructor(readonly workCellId: WorkCellId) {}
}

// =============================================================================
// Service Shape Interface
// =============================================================================

/**
 * WorkCell State Service Shape
 *
 * Contract for work cell state storage. Implementations must provide
 * consistent behavior for get/set/list/delete operations.
 */
export interface WorkCellStateShape {
  /** Create a new work cell (ID generated by implementation) */
  readonly create: (params: CreateWorkCellParams) => Effect.Effect<WorkCell>

  /** Get work cell by ID */
  readonly get: (id: WorkCellId) => Effect.Effect<WorkCell, WorkCellStateNotFoundError>

  /** Set/update work cell state (upsert) - use for updates, not creates */
  readonly set: (workCell: WorkCell) => Effect.Effect<void>

  /** List work cells matching filter */
  readonly list: (filter: WorkCellFilter) => Effect.Effect<readonly WorkCell[]>

  /** Delete work cell by ID */
  readonly delete: (id: WorkCellId) => Effect.Effect<boolean>

  /** Check if work cell exists */
  readonly exists: (id: WorkCellId) => Effect.Effect<boolean>

  /** Count work cells matching filter */
  readonly count: (filter: WorkCellFilter) => Effect.Effect<number>
}

// =============================================================================
// Service Definition
// =============================================================================

/**
 * WorkCellState Service Tag
 *
 * Usage:
 * ```ts
 * const program = Effect.gen(function* () {
 *   const state = yield* WorkCellState
 *   const workCell = yield* state.get(workCellId)
 * })
 * ```
 */
export class WorkCellState extends Context.Tag('iiot/WorkCellState')<
  WorkCellState,
  WorkCellStateShape
>() {}

// =============================================================================
// In-Memory Implementation
// =============================================================================

/**
 * In-memory work cell state implementation for testing.
 *
 * Uses a Map for O(1) lookup. Not suitable for production due to:
 * - No persistence
 * - No cross-process sharing
 * - Memory limits
 */
export const WorkCellStateInMemory: Layer.Layer<WorkCellState> = Layer.effect(
  WorkCellState,
  Ref.make(new Map<WorkCellId, WorkCell>()).pipe(
    Effect.map((store) => {
      const matchesFilter = (workCell: WorkCell, filter: WorkCellFilter): boolean => {
        if (filter.lineId && workCell.lineId !== Option.some(filter.lineId)) {
          // Check if lineId matches (lineId in WorkCell is Option<LineId> from BaseAssetFields)
          if (Option.isNone(workCell.lineId) || workCell.lineId.value !== filter.lineId) {
            return false
          }
        }
        if (filter.status && workCell.status !== filter.status) return false
        if (filter.cellType) {
          if (Option.isNone(workCell.cellType) || workCell.cellType.value !== filter.cellType) {
            return false
          }
        }
        if (filter.onlyOperational && !workCell.isOperational()) return false
        if (filter.since) {
          const sinceMs = filter.since.getTime()
          const workCellMs = Number(workCell.createdAt.epochMillis)
          if (workCellMs < sinceMs) return false
        }
        if (filter.until) {
          const untilMs = filter.until.getTime()
          const workCellMs = Number(workCell.createdAt.epochMillis)
          if (workCellMs > untilMs) return false
        }
        return true
      }

      return {
        create: (params: CreateWorkCellParams) =>
          Effect.gen(function* () {
            const id = generateWorkCellId()
            const now = yield* DateTime.now
            const workCell = new WorkCell({
              id,
              name: params.name,
              status: params.status ?? 'idle',
              description: params.description !== undefined ? Option.some(params.description) : Option.none(),
              location: Option.none(),
              metadata: params.metadata ?? {},
              createdAt: now,
              updatedAt: Option.none(),
              hierarchyPath: HierarchyPath.empty(),
              enterpriseId: Option.none(),
              siteId: Option.none(),
              areaId: Option.none(),
              plantId: Option.none(),
              lineId: Option.some(params.lineId),
              workCellId: Option.none(),
              machineId: Option.none(),
              cellType: params.cellType !== undefined ? Option.some(params.cellType) : Option.none(),
              cycleTimeSeconds: params.cycleTimeSeconds !== undefined ? Option.some(params.cycleTimeSeconds) : Option.none(),
              position: params.position !== undefined ? Option.some(params.position) : Option.none(),
            })
            yield* Ref.update(store, (map) => {
              const newMap = new Map(map)
              newMap.set(id, workCell)
              return newMap
            })
            return workCell
          }),

        get: (id: WorkCellId) =>
          Ref.get(store).pipe(
            Effect.flatMap((map) => {
              const workCell = map.get(id)
              if (!workCell) {
                return Effect.fail(new WorkCellStateNotFoundError(id))
              }
              return Effect.succeed(workCell)
            })
          ),

        set: (workCell: WorkCell) =>
          Ref.update(store, (map) => {
            const newMap = new Map(map)
            newMap.set(workCell.id, workCell)
            return newMap
          }),

        list: (filter: WorkCellFilter) =>
          Ref.get(store).pipe(
            Effect.map((map) => {
              let workCells = Array.from(map.values()).filter((wc) =>
                matchesFilter(wc, filter)
              )

              // Sort by createdAt descending
              workCells.sort((a, b) =>
                Number(b.createdAt.epochMillis) - Number(a.createdAt.epochMillis)
              )

              // Apply pagination
              if (filter.offset) {
                workCells = workCells.slice(filter.offset)
              }
              if (filter.limit) {
                workCells = workCells.slice(0, filter.limit)
              }

              return workCells
            })
          ),

        delete: (id: WorkCellId) =>
          Ref.modify(store, (map) => {
            const existed = map.has(id)
            if (existed) {
              const newMap = new Map(map)
              newMap.delete(id)
              return [true, newMap] as const
            }
            return [false, map] as const
          }),

        exists: (id: WorkCellId) =>
          Ref.get(store).pipe(Effect.map((map) => map.has(id))),

        count: (filter: WorkCellFilter) =>
          Ref.get(store).pipe(
            Effect.map((map) =>
              Array.from(map.values()).filter((wc) => matchesFilter(wc, filter)).length
            )
          ),
      }
    })
  )
)

