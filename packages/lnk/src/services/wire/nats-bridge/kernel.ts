/**
 * Durable Stream kernel for the MSH-backed bridge.
 *
 * This module is deliberately pure LNK domain logic. It knows nothing about
 * NATS clients, JetStream handles, KV buckets, or MSH implementation details.
 * The live bridge feeds it revisioned metadata loaded from the typed MSH KV
 * service, publishes the returned `DurableBatchEnvelope`, then commits the
 * returned metadata via KV CAS. Substrate downstairs, protocol law up here.
 *
 * @module @tmnl/lnk/services/wire/nats-bridge/kernel
 */

