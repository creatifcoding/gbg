/**
 * SQL-backed line state implementation for production.
 *
 * Uses a repository for actual SQL operations.
 * This factory bridges the state interface to the repository pattern.
 *
 * @param repo - Repository with SQL-backed operations
 * @returns LineStateShape implementation
 */
export const makeLineStateSql = (repo: {
  findById: (id: LineId) => Effect.Effect<Option.Option<Line>, unknown>
  findAll: (filter: LineFilter) => Effect.Effect<readonly Line[], unknown>
  insert: (line: Line) => Effect.Effect<Line, unknown>
  update: (line: Partial<Line> & { id: LineId }) => Effect.Effect<Line, unknown>
  delete: (id: LineId) => Effect.Effect<boolean, unknown>
  /** Insert with DB-generated ID. If not provided, falls back to insert() */
  insertWithGeneratedId?: (params: CreateLineParams) => Effect.Effect<Line, unknown>
}): LineStateShape => ({
  create: (params: CreateLineParams) =>
    repo.insertWithGeneratedId
      ? repo.insertWithGeneratedId(params).pipe(
          Effect.orDie // SQL failures are defects
        )
      : Effect.gen(function* () {
          // Fallback: generate ID client-side if repo doesn't support generated IDs
          const id = generateLineId()
          const now = yield* DateTime.now

          const segments: PathSegment[] = [
            new PathSegment({ level: 'plant', id: params.plantId, name: Option.none() }),
            new PathSegment({ level: 'line', id, name: Option.some(params.name) }),
          ]

          const line = new Line({
            id,
            name: params.name,
            status: params.status ?? 'idle',
            hierarchyPath: HierarchyPath.fromSegments(segments),
            enterpriseId: Option.none(),
            siteId: Option.none(),
            areaId: Option.none(),
            plantId: Option.some(params.plantId),
            lineId: Option.none(),
            workCellId: Option.none(),
            machineId: Option.none(),
            createdAt: now,
            updatedAt: Option.none(),
            description: params.description !== undefined
              ? Option.some(params.description)
              : Option.none(),
            location: Option.none(),
            metadata: params.metadata ?? {},
            capacity: params.capacity !== undefined
              ? Option.some(params.capacity)
              : Option.none(),
            lineType: params.lineType !== undefined
              ? Option.some(params.lineType)
              : Option.none(),
            operatingHoursPerDay: params.operatingHoursPerDay !== undefined
              ? Option.some(params.operatingHoursPerDay)
              : Option.none(),
          })
          return yield* repo.insert(line).pipe(Effect.orDie)
        }),

  get: (id) =>
    repo.findById(id).pipe(
      Effect.flatMap((opt) =>
        Option.isSome(opt)
          ? Effect.succeed(opt.value)
          : Effect.fail(new LineStateNotFoundError(id))
      ),
      Effect.catchAll(() => Effect.fail(new LineStateNotFoundError(id)))
    ),

  set: (line) =>
    repo.findById(line.id).pipe(
      Effect.flatMap((existing) =>
        Option.isSome(existing)
          ? repo.update(line as Partial<Line> & { id: LineId })
          : repo.insert(line)
      ),
      Effect.asVoid,
      Effect.catchAll(() => Effect.void)
    ),

  list: (filter) =>
    repo.findAll(filter).pipe(
      Effect.catchAll(() => Effect.succeed([]))
    ),

  delete: (id) =>
    repo.delete(id).pipe(
      Effect.catchAll(() => Effect.succeed(false))
    ),

  exists: (id) =>
    repo.findById(id).pipe(
      Effect.map(Option.isSome),
      Effect.catchAll(() => Effect.succeed(false))
    ),

  count: (filter) =>
    repo.findAll({ ...filter, limit: undefined, offset: undefined }).pipe(
      Effect.map((lines) => lines.length),
      Effect.catchAll(() => Effect.succeed(0))
    ),
})
