/**
 * State Service Shape Interfaces
 *
 * Defines the contracts for state services that can be swapped between
 * in-memory (testing) and SQL (production) implementations.
 *
 * Design Principles:
 * - All methods return Effect for consistent async handling
 * - Read methods return Option for nullable results
 * - Write methods are idempotent where possible
 * - Filter types are defined per-domain for type safety
 *
 * @module
 */

import { Effect, Option } from 'effect'
import type {
  AlarmId,
  WorkOrderId,
  MachineId,
  LineId,
  WorkCellId,
} from '../schemas/identifiers'
import type { Alarm, AlarmState as AlarmStateType, CreateAlarmParams } from '../schemas/alarms'
import type { WorkOrder, WorkOrderStatus } from '../schemas/work-orders'
import type {
  EquipmentStateId,
  EquipmentState,
  StateType,
  StateReason,
} from '../schemas/equipment-state/schema'
import type { WorkCell, CreateWorkCellParams } from '../schemas/assets/workcell'

// =============================================================================
// Create Input Types (without ID - for DB-generated IDs)
// =============================================================================

/** Input for creating a new work order (ID generated by DB) */
export interface CreateWorkOrderInput {
  readonly workflowDefinitionId: string
  readonly workflowVersion: string
  readonly type: string
  readonly priority: string
  readonly title: string
  readonly description: string
  readonly createdBy: string
  readonly scheduledStart: Option.Option<Date>
  readonly dueDate: Option.Option<Date>
  readonly parentWorkOrderId: Option.Option<string>
  readonly primaryAssetId: Option.Option<string>
  readonly assignedTo: Option.Option<string>
  readonly metadata?: Record<string, unknown>
}

/** Input for creating a new equipment state (ID generated by DB) */
export interface CreateEquipmentStateInput {
  readonly machineId: MachineId
  readonly state: StateType
  readonly reason: Option.Option<StateReason>
  readonly operatorId: Option.Option<string>
  readonly notes: Option.Option<string>
}

// =============================================================================
// Common Types
// =============================================================================

/** Pagination options */
export interface PaginationOptions {
  readonly limit?: number
  readonly offset?: number
}

/** Time range filter */
export interface TimeRangeFilter {
  readonly since?: Date
  readonly until?: Date
}

// =============================================================================
// Alarm State Shape
// =============================================================================

/** Filter for listing alarms */
export interface AlarmFilter extends PaginationOptions, TimeRangeFilter {
  readonly deviceId?: string
  readonly assetId?: string
  readonly severity?: string
  readonly state?: AlarmStateType
  readonly onlyActive?: boolean
  readonly onlyRequiresAttention?: boolean
}

/** Alarm state not found error */
export class AlarmStateNotFoundError {
  readonly _tag = 'AlarmStateNotFoundError'
  constructor(readonly alarmId: AlarmId) {}
}

/**
 * Alarm State Service Shape
 *
 * Contract for alarm state storage. Implementations must provide
 * consistent behavior for get/set/list/delete operations.
 */
export interface AlarmStateShape {
  /** Create a new alarm (ID generated by implementation) */
  readonly create: (params: CreateAlarmParams) => Effect.Effect<Alarm>

  /** Get alarm by ID */
  readonly get: (id: AlarmId) => Effect.Effect<Alarm, AlarmStateNotFoundError>

  /** Set/update alarm state (upsert) - use for updates, not creates */
  readonly set: (alarm: Alarm) => Effect.Effect<void>

  /** List alarms matching filter */
  readonly list: (filter: AlarmFilter) => Effect.Effect<readonly Alarm[]>

  /** Delete alarm by ID */
  readonly delete: (id: AlarmId) => Effect.Effect<boolean>

  /** Check if alarm exists */
  readonly exists: (id: AlarmId) => Effect.Effect<boolean>

  /** Count alarms matching filter */
  readonly count: (filter: AlarmFilter) => Effect.Effect<number>
}

