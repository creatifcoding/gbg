/**
 * SQL-backed device state implementation for production.
 *
 * Uses the existing DeviceRepo for actual SQL operations.
 * This factory bridges the state interface to the repository pattern.
 *
 * For the full SQL implementation, see DeviceRepo.
 */
export const makeDeviceStateSql = (repo: {
  findById: (id: DeviceId) => Effect.Effect<Option.Option<Device>, unknown>
  findAll: (filter: DeviceFilter) => Effect.Effect<readonly Device[], unknown>
  insert: (device: Device) => Effect.Effect<Device, unknown>
  update: (device: Partial<Device> & { id: DeviceId }) => Effect.Effect<Device, unknown>
  delete: (id: DeviceId) => Effect.Effect<boolean, unknown>
  /** Insert with DB-generated ID. If not provided, falls back to insert() */
  insertWithGeneratedId?: (params: CreateDeviceParams) => Effect.Effect<Device, unknown>
}): DeviceStateShape => ({
  create: (params: CreateDeviceParams) =>
    repo.insertWithGeneratedId
      ? repo.insertWithGeneratedId(params).pipe(
          Effect.orDie // SQL failures are defects
        )
      : Effect.gen(function* () {
          // Fallback: generate ID client-side if repo doesn't support generated IDs
          const id = params.slug
            ? makeDeviceId(params.slug)
            : generateDeviceId()
          const now = yield* DateTime.now

          // Build hierarchy path for device
          const hierarchyPath = HierarchyPath.fromSegments([
            new PathSegment({
              level: 'machine',
              id: params.machineId,
              name: Option.none(),
            }),
            new PathSegment({
              level: 'device',
              id: id,
              name: Option.some(params.name as typeof Schema.NonEmptyString.Type),
            }),
          ])

          const device = new Device({
            id,
            name: params.name,
            status: params.status ?? 'active',
            machineId: Option.some(params.machineId),
            deviceType: params.deviceType,
            controlMode: params.controlMode ? Option.some(params.controlMode) : Option.none(),
            ratedPower: params.ratedPower ? Option.some(params.ratedPower) : Option.none(),
            powerUnit: params.powerUnit ? Option.some(params.powerUnit) : Option.none(),
            lastCommandAt: Option.none(),
            opcUaNodeId: params.opcUaNodeId ? Option.some(params.opcUaNodeId) : Option.none(),
            description: params.description ? Option.some(params.description) : Option.none(),
            createdAt: now,
            updatedAt: Option.none(),
            metadata: params.metadata ?? {},
            hierarchyPath,
            enterpriseId: Option.none(),
            siteId: Option.none(),
            areaId: Option.none(),
            plantId: Option.none(),
            lineId: Option.none(),
            workCellId: Option.none(),
            location: Option.none(),
          })

          return yield* repo.insert(device).pipe(Effect.orDie)
        }),

  get: (id) =>
    repo.findById(id).pipe(
      Effect.flatMap((opt) =>
        Option.isSome(opt)
          ? Effect.succeed(opt.value)
          : Effect.fail(new DeviceStateNotFoundError(id))
      ),
      Effect.catchAll(() => Effect.fail(new DeviceStateNotFoundError(id)))
    ),

  set: (device) =>
    repo.findById(device.id).pipe(
      Effect.flatMap((existing) =>
        Option.isSome(existing)
          ? repo.update(device as Partial<Device> & { id: DeviceId })
          : repo.insert(device)
      ),
      Effect.asVoid,
      Effect.catchAll(() => Effect.void)
    ),

  list: (filter) =>
    repo.findAll(filter).pipe(
      Effect.catchAll(() => Effect.succeed([]))
    ),

  delete: (id) =>
    repo.delete(id).pipe(
      Effect.catchAll(() => Effect.succeed(false))
    ),

  exists: (id) =>
    repo.findById(id).pipe(
      Effect.map(Option.isSome),
      Effect.catchAll(() => Effect.succeed(false))
    ),

  count: (filter) =>
    repo.findAll({ ...filter, limit: undefined, offset: undefined }).pipe(
      Effect.map((devices) => devices.length),
      Effect.catchAll(() => Effect.succeed(0))
    ),
})
