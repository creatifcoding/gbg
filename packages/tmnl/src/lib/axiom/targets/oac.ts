/**
 * Generate the ontology module files without package scaffolding.
 *
 * Returns a map of file paths to contents.
 */
export const generateOntologyModule = (
  config: OntologyModuleConfig
): Effect.Effect<OntologyModule, CompileError> => {
  const { namespace, schemas, includeLinks = true } = config

  // Compile all schemas to OSDK definitions
  return Effect.flatMap(Effect.all(schemas.map(compileToOSDK)), (defs) => {
    const files = new Map<string, string>()

    // Generate object files
    for (const def of defs) {
      files.set(`ontology/objects/${def.apiName}.ts`, generateObjectFile(def))
    }

    // Generate objects index
    files.set("ontology/objects/index.ts", generateObjectsIndex(defs))

    // Extract and generate links if requested
    if (!includeLinks) {
      files.set("ontology/links/index.ts", generateLinksIndex([]))
      files.set(
        "ontology/index.ts",
        generateOntologyIndex(defs, [])
      )
      return Effect.succeed({
        files,
        entrypoint: "ontology/index.ts",
      })
    }

    // Build object definitions map for link extraction
    const objectDefMap = new Map(defs.map((d) => [d.apiName, d]))

    // Extract links from all schemas
    const linkInfos: LinkInfo[] = []
    for (const schema of schemas) {
      const fields = schema._fields as Record<string, Record<string, unknown>>

      for (const [key, field] of globalThis.Object.entries(fields)) {
        if (!isLink(field)) continue

        const linkField = field as unknown as LinkType<unknown, LinkCardinality>
        const targetSchema = linkField._target() as ObjectSchema<
          string,
          FieldRecord
        >
        const cardinality = linkField._cardinality

        linkInfos.push({
          apiName: `${schema._name}To${targetSchema._name}`,
          sourceName: schema._name,
          targetName: targetSchema._name,
          cardinality,
          foreignKeyProperty:
            cardinality === "many-to-one" ? key : undefined,
        })
      }
    }

    // Generate link files
    for (const link of linkInfos) {
      files.set(`ontology/links/${link.apiName}.ts`, generateLinkFile(link))
    }

    // Generate links index
    files.set("ontology/links/index.ts", generateLinksIndex(linkInfos))

    // Generate main index
    files.set("ontology/index.ts", generateOntologyIndex(defs, linkInfos))

    return Effect.succeed({
      files,
      entrypoint: "ontology/index.ts",
    })
  })
}

