/**
 * JsonRenderBlock Schema
 *
 * Block type for rendering rich json-render UI trees within the terminal.
 * Enables hybrid terminal that can render both text/markdown responses
 * and structured UI components via the json-render system.
 *
 * @module terminal/v3/schemas/json-render-block
 */

import { Schema } from 'effect'
import type { UITree, JsonPatch } from '@/lib/json-render/core/schemas'

// =============================================================================
// Semantic Region Entry
// =============================================================================

/**
 * Entry describing a semantic region within the UI tree.
 * Used by agents to discover and target specific regions for transformation.
 */
export const SemanticRegionEntry = Schema.Struct({
  /** Unique region ID (matches data-semantic-id attribute) */
  id: Schema.String,
  /** Human-readable label (matches data-semantic-label attribute) */
  label: Schema.String,
  /** Region type for categorization */
  type: Schema.optional(Schema.String),
  /** Key of the element in the UITree that contains this region */
  elementKey: Schema.optional(Schema.String),
})
export type SemanticRegionEntry = typeof SemanticRegionEntry.Type

// =============================================================================
// JsonRenderBlock Schema
// =============================================================================

/**
 * JsonRenderBlock v3 - Rich UI rendering block
 *
 * This block type enables the terminal to render structured UI components
 * generated by AI tools using the json-render system. It supports:
 *
 * - Progressive streaming via patches
 * - Semantic regions for agent targeting
 * - Integration with the combined catalog (RVN + layout components)
 *
 * @example
 * ```tsx
 * // Creating a json-render block
 * const block = createJsonRenderBlock()
 *
 * // With initial tree
 * const block = createJsonRenderBlock(initialTree, true) // isStreaming = true
 *
 * // Rendering
 * <JsonRenderBlockComponent block={block} />
 * ```
 */
export const JsonRenderBlockV3 = Schema.TaggedStruct('json-render', {
  /** Unique block identifier */
  id: Schema.String,
  /** When the block was created */
  timestamp: Schema.DateFromSelf,
  /**
   * The UI tree to render.
   * null when streaming hasn't started or tree is being rebuilt.
   */
  uiTree: Schema.NullOr(Schema.Unknown), // UITree type - using Unknown for flexibility
  /**
   * Accumulated patches applied to the tree.
   * Useful for debugging and replay.
   */
  patches: Schema.Array(Schema.Unknown), // JsonPatch[] - using Unknown for flexibility
  /**
   * Whether the UI tree is currently streaming/updating.
   * Used to show loading states and defer certain interactions.
   */
  isStreaming: Schema.Boolean,
  /**
   * Discovered semantic regions within the UI tree.
   * Populated by scanning the tree for SemanticRegion elements.
   */
  semanticRegions: Schema.Array(SemanticRegionEntry),
})
export type JsonRenderBlockV3 = typeof JsonRenderBlockV3.Type

// =============================================================================
// Type Guard
// =============================================================================

/**
 * Type guard for JsonRenderBlock
 */
export const isJsonRenderBlock = (block: { _tag: string }): block is JsonRenderBlockV3 =>
  block._tag === 'json-render'

// =============================================================================
// Factory
// =============================================================================

let blockCounter = 0

const generateBlockId = (): string => {
  blockCounter++
  return `jsonrender-${Date.now()}-${blockCounter.toString(36)}`
}

/**
 * Create a new JsonRenderBlock
 *
 * @param uiTree - Initial UI tree (null if streaming)
 * @param isStreaming - Whether the block is in streaming mode
 * @returns A new JsonRenderBlockV3 instance
 */
export const createJsonRenderBlock = (
  uiTree: UITree | null = null,
  isStreaming: boolean = false,
): JsonRenderBlockV3 => ({
  _tag: 'json-render',
  id: generateBlockId(),
  timestamp: new Date(),
  uiTree: uiTree as unknown, // Cast to unknown for schema compatibility
  patches: [],
  isStreaming,
  semanticRegions: [],
})

/**
 * Create a JsonRenderBlock with semantic regions
 *
 * @param uiTree - The UI tree
 * @param semanticRegions - Pre-scanned semantic regions
 * @param isStreaming - Whether streaming is active
 * @returns A new JsonRenderBlockV3 instance
 */
export const createJsonRenderBlockWithRegions = (
  uiTree: UITree | null,
  semanticRegions: SemanticRegionEntry[],
  isStreaming: boolean = false,
): JsonRenderBlockV3 => ({
  _tag: 'json-render',
  id: generateBlockId(),
  timestamp: new Date(),
  uiTree: uiTree as unknown,
  patches: [],
  isStreaming,
  semanticRegions,
})
