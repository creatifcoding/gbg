/**
 * Factory to create SQL-backed area state from a repository.
 *
 * Bridges the state interface to the repository pattern.
 * For the full SQL implementation, see AreaRepo.
 */
export const makeAreaStateSql = (repo: {
  findById: (id: AreaId) => Effect.Effect<Option.Option<Area>, unknown>
  findAll: (filter: AreaFilter) => Effect.Effect<readonly Area[], unknown>
  insert: (area: Area) => Effect.Effect<Area, unknown>
  update: (area: Partial<Area> & { id: AreaId }) => Effect.Effect<Area, unknown>
  delete: (id: AreaId) => Effect.Effect<boolean, unknown>
  /** Insert with DB-generated ID. If not provided, falls back to insert() */
  insertWithGeneratedId?: (params: CreateAreaParams) => Effect.Effect<Area, unknown>
}): AreaStateShape => ({
  create: (params: CreateAreaParams) =>
    repo.insertWithGeneratedId
      ? repo.insertWithGeneratedId(params).pipe(Effect.orDie)
      : Effect.gen(function* () {
          // Fallback: generate ID client-side if repo doesn't support generated IDs
          const id = generateAreaId()
          const now = yield* DateTime.now

          // Build hierarchy path from parent references
          const hierarchyPath = HierarchyPath.make({
            segments: [
              PathSegment.make({ level: 'site', id: params.siteId }),
              PathSegment.make({ level: 'area', id }),
            ],
            materialized: `${params.siteId}/${id}`,
          })

          const area = new Area({
            id,
            name: params.name,
            status: Option.getOrElse(params.status, () => 'active' as const),
            siteId: params.siteId,
            enterpriseId: 'ENT-default' as EnterpriseId,
            areaType: params.areaType !== undefined ? Option.some(params.areaType) : Option.none(),
            building: params.building !== undefined ? Option.some(params.building) : Option.none(),
            floor: params.floor !== undefined ? Option.some(params.floor) : Option.none(),
            zone: params.zone !== undefined ? Option.some(params.zone) : Option.none(),
            description: params.description !== undefined ? Option.some(params.description) : Option.none(),
            createdAt: now,
            updatedAt: Option.none(),
            metadata: params.metadata ?? {},
            hierarchyPath,
            location: Option.none(),
          })
          return yield* repo.insert(area).pipe(Effect.orDie)
        }),

  get: (id) =>
    repo.findById(id).pipe(
      Effect.flatMap((opt) =>
        Option.isSome(opt)
          ? Effect.succeed(opt.value)
          : Effect.fail(new AreaStateNotFoundError(id))
      ),
      Effect.catchAll(() => Effect.fail(new AreaStateNotFoundError(id)))
    ),

  set: (area) =>
    repo.findById(area.id).pipe(
      Effect.flatMap((existing) =>
        Option.isSome(existing)
          ? repo.update(area as Partial<Area> & { id: AreaId })
          : repo.insert(area)
      ),
      Effect.asVoid,
      Effect.catchAll(() => Effect.void)
    ),

  list: (filter) =>
    repo.findAll(filter).pipe(
      Effect.catchAll(() => Effect.succeed([]))
    ),

  delete: (id) =>
    repo.delete(id).pipe(
      Effect.catchAll(() => Effect.succeed(false))
    ),

  exists: (id) =>
    repo.findById(id).pipe(
      Effect.map(Option.isSome),
      Effect.catchAll(() => Effect.succeed(false))
    ),

  count: (filter) =>
    repo.findAll({ ...filter, limit: undefined, offset: undefined }).pipe(
      Effect.map((areas) => areas.length),
      Effect.catchAll(() => Effect.succeed(0))
    ),
})
