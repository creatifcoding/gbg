// SQL Factory
// =============================================================================

/**
 * Factory to create SQL-backed enterprise state from a repository.
 *
 * Bridges the state interface to the repository pattern.
 *
 * @param repo - Repository with SQL-backed operations
 * @returns EnterpriseStateShape implementation
 */
export const makeEnterpriseStateSql = (repo: {
  findById: (id: EnterpriseId) => Effect.Effect<Option.Option<Enterprise>, unknown>
  findAll: (filter: EnterpriseFilter) => Effect.Effect<readonly Enterprise[], unknown>
  insert: (enterprise: Enterprise) => Effect.Effect<Enterprise, unknown>
  update: (enterprise: Partial<Enterprise> & { id: EnterpriseId }) => Effect.Effect<Enterprise, unknown>
  delete: (id: EnterpriseId) => Effect.Effect<boolean, unknown>
  /** Insert with DB-generated ID. If not provided, falls back to insert() */
  insertWithGeneratedId?: (params: CreateEnterpriseParams) => Effect.Effect<Enterprise, unknown>
}): EnterpriseStateShape => ({
  create: (params: CreateEnterpriseParams) =>
    repo.insertWithGeneratedId
      ? repo.insertWithGeneratedId(params).pipe(Effect.orDie)
      : Effect.gen(function* () {
          // Fallback: generate ID client-side if repo doesn't support generated IDs
          const id = generateEnterpriseId()
          const now = yield* DateTime.now

          // Build hierarchy path - Enterprise is root level
          const hierarchyPath = HierarchyPath.root(id, params.name)

          const enterprise = new Enterprise({
            id,
            name: params.name,
            status: Option.getOrElse(params.status, () => 'active' as const),
            description: params.description,
            industry: params.industry,
            legalName: params.legalName,
            taxId: params.taxId,
            headquarters: params.headquarters,
            hierarchyPath,
            createdAt: now,
            updatedAt: Option.none(),
            location: Option.none(),
            metadata: Option.getOrElse(params.metadata, () => ({})),
            // Enterprise has no parent IDs (it's the root)
            enterpriseId: Option.none(),
            siteId: Option.none(),
            areaId: Option.none(),
            plantId: Option.none(),
            lineId: Option.none(),
            workCellId: Option.none(),
            machineId: Option.none(),
          })

          return yield* repo.insert(enterprise).pipe(Effect.orDie)
        }),

  get: (id) =>
    repo.findById(id).pipe(
      Effect.flatMap((opt) =>
        Option.isSome(opt)
          ? Effect.succeed(opt.value)
          : Effect.fail(new EnterpriseStateNotFoundError(id))
      ),
      Effect.catchAll(() => Effect.fail(new EnterpriseStateNotFoundError(id)))
    ),

  set: (enterprise) =>
    repo.findById(enterprise.id).pipe(
      Effect.flatMap((existing) =>
        Option.isSome(existing)
          ? repo.update(enterprise as Partial<Enterprise> & { id: EnterpriseId })
          : repo.insert(enterprise)
      ),
      Effect.asVoid,
      Effect.catchAll(() => Effect.void)
    ),

  list: (filter) =>
    repo.findAll(filter).pipe(
      Effect.catchAll(() => Effect.succeed([]))
    ),

  delete: (id) =>
    repo.delete(id).pipe(
      Effect.catchAll(() => Effect.succeed(false))
    ),

  exists: (id) =>
    repo.findById(id).pipe(
      Effect.map(Option.isSome),
      Effect.catchAll(() => Effect.succeed(false))
    ),

  count: (filter) =>
    repo.findAll({ ...filter, limit: undefined, offset: undefined }).pipe(
      Effect.map((enterprises) => enterprises.length),
      Effect.catchAll(() => Effect.succeed(0))
    ),
})
