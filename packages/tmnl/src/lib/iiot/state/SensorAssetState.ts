/**
 * SQL-backed sensor asset state implementation for production.
 *
 * Uses the existing SensorRepo for actual SQL operations.
 * This layer bridges the state interface to the repository pattern.
 *
 * For the full SQL implementation, see SensorRepo.
 */
export const makeSensorAssetStateSql = (repo: {
  findById: (id: SensorId) => Effect.Effect<Option.Option<Sensor>, unknown>
  findAll: (filter: SensorAssetFilter) => Effect.Effect<readonly Sensor[], unknown>
  insert: (sensor: Sensor) => Effect.Effect<Sensor, unknown>
  update: (sensor: Partial<Sensor> & { id: SensorId }) => Effect.Effect<Sensor, unknown>
  delete: (id: SensorId) => Effect.Effect<boolean, unknown>
  /** Insert with params and generate ID. If not provided, falls back to insert() */
  insertWithGeneratedId?: (params: CreateSensorParams) => Effect.Effect<Sensor, unknown>
}): SensorAssetStateShape => ({
  create: (params: CreateSensorParams) =>
    repo.insertWithGeneratedId
      ? repo.insertWithGeneratedId(params).pipe(
          Effect.orDie // SQL failures are defects
        )
      : Effect.gen(function* () {
          // Fallback: generate ID client-side if repo doesn't support generated IDs
          const id = makeSensorId(params.slug)
          const now = yield* DateTime.now

          // Build hierarchy path from machineId
          const segments: PathSegment[] = [
            new PathSegment({
              level: 'machine',
              id: params.machineId,
              name: 'Machine',
            }),
            new PathSegment({
              level: 'sensor',
              id,
              name: params.name,
            }),
          ]

          const sensor = new Sensor({
            id,
            name: params.name,
            status: params.status ?? 'active',
            hierarchyPath: HierarchyPath.fromSegments(segments),
            machineId: Option.some(params.machineId),
            sensorType: params.sensorType,
            unit: params.unit,
            sampleRateMs: params.sampleRateMs !== undefined ? Option.some(params.sampleRateMs) : Option.none(),
            thresholdHigh: params.thresholdHigh !== undefined ? Option.some(params.thresholdHigh) : Option.none(),
            thresholdCritical: params.thresholdCritical !== undefined ? Option.some(params.thresholdCritical) : Option.none(),
            thresholdLow: params.thresholdLow !== undefined ? Option.some(params.thresholdLow) : Option.none(),
            thresholdCriticalLow: params.thresholdCriticalLow !== undefined ? Option.some(params.thresholdCriticalLow) : Option.none(),
            lastCalibrationDate: Option.none(),
            nextCalibrationDate: Option.none(),
            opcUaNodeId: params.opcUaNodeId !== undefined ? Option.some(params.opcUaNodeId) : Option.none(),
            description: params.description !== undefined ? Option.some(params.description) : Option.none(),
            location: Option.none(),
            metadata: params.metadata ?? {},
            createdAt: now,
            updatedAt: Option.none(),
            enterpriseId: Option.none(),
            siteId: Option.none(),
            areaId: Option.none(),
            plantId: Option.none(),
            lineId: Option.none(),
            workCellId: Option.none(),
          })

          return yield* repo.insert(sensor).pipe(Effect.orDie)
        }),

  get: (id) =>
    repo.findById(id).pipe(
      Effect.flatMap((opt) =>
        Option.isSome(opt)
          ? Effect.succeed(opt.value)
          : Effect.fail(new SensorAssetStateNotFoundError(id))
      ),
      Effect.catchAll(() => Effect.fail(new SensorAssetStateNotFoundError(id)))
    ),

  set: (sensor) =>
    repo.findById(sensor.id).pipe(
      Effect.flatMap((existing) =>
        Option.isSome(existing)
          ? repo.update(sensor as Partial<Sensor> & { id: SensorId })
          : repo.insert(sensor)
      ),
      Effect.asVoid,
      Effect.catchAll(() => Effect.void)
    ),

  list: (filter) =>
    repo.findAll(filter).pipe(
      Effect.catchAll(() => Effect.succeed([]))
    ),

  delete: (id) =>
    repo.delete(id).pipe(
      Effect.catchAll(() => Effect.succeed(false))
    ),

  exists: (id) =>
    repo.findById(id).pipe(
      Effect.map(Option.isSome),
      Effect.catchAll(() => Effect.succeed(false))
    ),

  count: (filter) =>
    repo.findAll({ ...filter, limit: undefined, offset: undefined }).pipe(
      Effect.map((sensors) => sensors.length),
      Effect.catchAll(() => Effect.succeed(0))
    ),
})
