/**
 * Configuration for generating a complete Ontology as Code repository
 */
export interface OntologyAsCodeConfig {
  /** Foundry namespace (e.g., "com.mycompany.") */
  readonly namespace: string
  /** Output directory path */
  readonly outputPath: string
  /** Axiom schemas to include */
  readonly schemas: readonly ObjectSchema<string, FieldRecord>[]
  /** npm package name (default: derived from namespace) */
  readonly packageName?: string
  /** Package version (default: "1.0.0") */
  readonly version?: string
  /** Package author */
  readonly author?: string
  /** Package description */
  readonly description?: string
  /** Include links in ontology (default: true) */
  readonly includeLinks?: boolean
}

/**
 * Configuration for generating just the ontology module (no package scaffolding)
 */
export interface OntologyModuleConfig {
  /** Foundry namespace */
  readonly namespace: string
  /** Axiom schemas */
  readonly schemas: readonly ObjectSchema<string, FieldRecord>[]
  /** Include links (default: true) */
  readonly includeLinks?: boolean
}

/**
 * Generated ontology module with file contents
 */
export interface OntologyModule {
  /** Map of file paths to contents */
  readonly files: ReadonlyMap<string, string>
  /** Main entrypoint file path */
  readonly entrypoint: string
}

