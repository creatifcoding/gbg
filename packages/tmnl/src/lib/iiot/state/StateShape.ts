// =============================================================================
// EquipmentState Shape
// =============================================================================

/** Filter for listing equipment states */
export interface EquipmentStateFilter extends PaginationOptions, TimeRangeFilter {
  readonly machineId?: MachineId
  readonly state?: StateType
  readonly reason?: string
  readonly onlyActive?: boolean
}

/** Equipment state not found error */
export class EquipmentStateNotFoundError {
  readonly _tag = 'EquipmentStateNotFoundError'
  constructor(readonly stateId: EquipmentStateId) {}
}

/** Machine state not found error */
export class MachineStateNotFoundError {
  readonly _tag = 'MachineStateNotFoundError'
  constructor(readonly machineId: MachineId) {}
}

/**
 * EquipmentState Service Shape
 *
 * Contract for equipment state storage. Tracks machine state transitions
 * for OEE calculations and downtime analysis.
 */
export interface EquipmentStateShapeInterface {
  /** Create a new equipment state (ID generated by implementation) */
  readonly create: (input: CreateEquipmentStateInput) => Effect.Effect<EquipmentState>

  /** Get equipment state by ID */
  readonly get: (id: EquipmentStateId) => Effect.Effect<EquipmentState, EquipmentStateNotFoundError>

  /** Get current (active) state for a machine */
  readonly getCurrent: (machineId: MachineId) => Effect.Effect<Option.Option<EquipmentState>>

  /** Set/update equipment state (upsert) - use for updates, not creates */
  readonly set: (state: EquipmentState) => Effect.Effect<void>

  /** List equipment states matching filter */
  readonly list: (filter: EquipmentStateFilter) => Effect.Effect<readonly EquipmentState[]>

  /** End current state for a machine (set endedAt) */
  readonly endCurrent: (machineId: MachineId, endedAt: Date) => Effect.Effect<boolean>

  /** Delete equipment state by ID */
  readonly delete: (id: EquipmentStateId) => Effect.Effect<boolean>

  /** Count states matching filter */
  readonly count: (filter: EquipmentStateFilter) => Effect.Effect<number>
}

